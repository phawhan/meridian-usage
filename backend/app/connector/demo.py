def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        port: int = s.getsockname()[1]
        return port


def _block(data: Any) -> str:
    return f"```json\n{json.dumps(data, indent=2)}\n```"


async def _call(url: str, user: str, tool: str, args: dict[str, Any]) -> tuple[bool, Any]:
    params = StdioServerParameters(
        command=sys.executable,
        args=["-m", "app.connector.main", "--user", user, "--env", "prod", "--api-url", url],
        cwd=REPO_ROOT / "backend",
    )
    async with Client(params) as client:
        result = await client.call_tool(tool, args)
    return bool(result.is_error), json.loads(result.content[0].text)  # type: ignore[union-attr]


async def _tool_names(url: str) -> list[str]:
    params = StdioServerParameters(
        command=sys.executable,
        args=["-m", "app.connector.main", "--user", PRIYA[0], "--env", "prod", "--api-url", url],
        cwd=REPO_ROOT / "backend",
    )
    async with Client(params) as client:
        return [t.name for t in (await client.list_tools()).tools]


async def _run(url: str) -> list[str]:
    lines = [
        "# Connector transcript (prod)",
        "",
        "Generated by `make demo-transcript`; do not edit. A fresh prod service on the starter"
        " data; for each step the connector is started over stdio as the named person, exactly"
        " as Claude Desktop starts it. Requests and responses are the MCP `tools/call`"
        " arguments and the JSON the model receives.",
        "",
        f"Tools listed: `{'`, `'.join(await _tool_names(url))}`",
    ]
    for (user, who), heading, tool, args in STEPS:
        is_error, body = await _call(url, user, tool, args)
        if isinstance(body, list):
            body = body[:3]
        lines += [
            "",
            f"## {heading}",
            "",
            f"As **{who}**: `{tool}`",
            "",
            _block(args),
            "",
            f"{'Error result' if is_error else 'Result'}:",
            "",
            _block(body),
        ]
    return lines


def _refusal_log(db: Path) -> list[str]:
    with closing(sqlite3.connect(db)) as conn:
        rows = conn.execute(
            "SELECT channel, caller, action, target_group, reason FROM access_denial ORDER BY id"
        ).fetchall()
    table = ["| channel | caller | action | group | reason |", "|---|---|---|---|---|"]
    table += [f"| {' | '.join(str(c) for c in row)} |" for row in rows]
    return [
        "",
        "## The service's refusal log (`access_denial`)",
        "",
        "Steps 2-4 were refused by the connector before any request reached the service, so"
        " they are only in the connector's stderr log. Step 5 reached the service, which"
        " refused it on the live switch and recorded it:",
        "",
        *table,
    ]


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        shutil.copytree(REPO_ROOT / "data", root / "data")
        port = _free_port()
        url = f"http://127.0.0.1:{port}"
        env = os.environ | {
            "APP_ENV": "prod",
            "DB_PATH": str(root / "prod.db"),
            "DATA_DIR": str(root / "data"),
        }
        service = subprocess.Popen(
            [sys.executable, "-m", "uvicorn", "app.main:app", "--port", str(port)],
            cwd=REPO_ROOT / "backend",
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        try:
            for _ in range(100):
                try:
                    if httpx2.get(f"{url}/api/v1/healthz").status_code == 200:
                        break
                except httpx2.HTTPError:
                    time.sleep(0.1)
            lines = anyio.run(_run, url) + _refusal_log(root / "prod.db")
        finally:
            service.terminate()
            service.wait(timeout=10)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
